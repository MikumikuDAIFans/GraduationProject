import { createI18n } from "vue-i18n";

export const SUPPORTED_LOCALES = ["zh-CN", "en-US"] as const;
export type SupportedLocale = (typeof SUPPORTED_LOCALES)[number];

const STORAGE_KEY = "workspace-locale";

function normalizeLocale(locale: string | null | undefined): SupportedLocale {
  if (locale === "en" || locale === "en-US") return "en-US";
  return "zh-CN";
}

export function getSavedLocale(): SupportedLocale {
  if (typeof window === "undefined") {
    return "zh-CN";
  }
  return normalizeLocale(window.localStorage.getItem(STORAGE_KEY) ?? window.navigator.language);
}

export function persistLocale(locale: SupportedLocale) {
  if (typeof window !== "undefined") {
    window.localStorage.setItem(STORAGE_KEY, locale);
  }
}

